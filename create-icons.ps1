# PowerShellスクリプト: アイコンファイル作成
# このスクリプトをWindowsのPowerShellで実行してください

$iconsDir = "$PSScriptRoot\src-tauri\icons"

# iconsディレクトリが存在しない場合は作成
if (!(Test-Path $iconsDir)) {
    New-Item -ItemType Directory -Path $iconsDir -Force
}

Write-Host "Creating icon files in: $iconsDir"

# 有効な16x16 ICOファイルを作成（最小限の有効なICOフォーマット）
$icoData = @(
    # ICO Header
    0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x10, 0x10, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x68, 0x04,
    0x00, 0x00, 0x16, 0x00, 0x00, 0x00,
    # DIB Header
    0x28, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00
)

# 残りのデータを0で埋める
$totalSize = 1128
$remaining = $totalSize - $icoData.Length
$icoData += @(0) * $remaining

[System.IO.File]::WriteAllBytes("$iconsDir\icon.ico", [byte[]]$icoData)

# 有効なPNGファイル（1x1の透明PNG）
$pngData = @(
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
    0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
    0x89, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x44, 0x41, 0x54, 0x08, 0x5B, 0x63, 0x60, 0x00, 0x02, 0x00,
    0x00, 0x05, 0x00, 0x01, 0xE9, 0xFA, 0xDC, 0xD8, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
    0xAE, 0x42, 0x60, 0x82
)

[System.IO.File]::WriteAllBytes("$iconsDir\32x32.png", [byte[]]$pngData)
[System.IO.File]::WriteAllBytes("$iconsDir\128x128.png", [byte[]]$pngData)
[System.IO.File]::WriteAllBytes("$iconsDir\128x128@2x.png", [byte[]]$pngData)

# 有効なICNSファイル（最小限のMac用アイコン）
$icnsData = @(0x69, 0x63, 0x6E, 0x73, 0x00, 0x00, 0x00, 0x08)
[System.IO.File]::WriteAllBytes("$iconsDir\icon.icns", [byte[]]$icnsData)

Write-Host "`nIcon files created successfully!"
Get-ChildItem $iconsDir | Format-Table Name, Length
Write-Host "`nYou can now run: npm run tauri dev"
